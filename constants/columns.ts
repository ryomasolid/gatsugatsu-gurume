/** slug からコラムを取得（存在しなければ undefined） */
export function getColumn(slug: string): Column | undefined {
  return COLUMNS.find((c) => c.slug === slug);
}

/** 全コラムの slug 一覧（静的生成・サイトマップ用） */
export function getColumnSlugs(): string[] {
  return COLUMNS.map((c) => c.slug);
}

/** 関連コラムを Column 配列で取得 */
export function getRelatedColumns(slug: string, limit = 3): Column[] {
  const column = getColumn(slug);
  if (!column) return [];
  const related = column.related
    .map((s) => getColumn(s))
    .filter((c): c is Column => c !== undefined);
  if (related.length >= limit) return related.slice(0, limit);
  // 関連が足りなければ他のコラムで補完する
  const fill = COLUMNS.filter(
    (c) => c.slug !== slug && !related.some((r) => r.slug === c.slug)
  );
  return [...related, ...fill].slice(0, limit);
}
