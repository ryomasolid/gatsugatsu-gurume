/**
 * 指定した駅・店名に対する編集部メモを返す（無ければ undefined）。
 * 駅固有メモ → チェーンメモの順で探す。
 */
export function getEditorialNote(
  stationName: string,
  shopName: string
): string | undefined {
  const stationEntries = STATION_NOTES[stationName];
  if (stationEntries) {
    const hit = stationEntries.find((e) => shopName.includes(e.pattern));
    if (hit) return hit.note;
  }
  const chainHit = CHAIN_NOTES.find((e) => shopName.includes(e.pattern));
  return chainHit?.note;
}
