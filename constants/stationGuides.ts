/** 指定した駅の編集部ガイド文を返す（未執筆の駅は undefined） */
export function getStationGuide(stationName: string): string | undefined {
  const guide = STATION_GUIDES[stationName];
  return guide && guide.length > 0 ? guide : undefined;
}

/**
 * 編集部ガイドを執筆済みの駅名一覧を返す。
 * インデックス対象（独自コンテンツを持つ駅）の判定・サイトマップ生成に使う。
 */
export function getGuideStationNames(): string[] {
  return Object.keys(STATION_GUIDES).filter(
    (name) => STATION_GUIDES[name] && STATION_GUIDES[name].length > 0
  );
}
